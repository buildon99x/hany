// @project-specific(Node/Vite/Tauri assumption — symlinks node_modules across worktrees)
import { spawnSync } from "node:child_process";
import { lstatSync, unlinkSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { cwd } from "node:process";

const SPAWN_TIMEOUT_MS = 5000;

process.on("uncaughtException", (err) => {
  log(`uncaughtException: ${err?.message ?? "unknown"}`);
  process.exit(0);
});

function log(line) {
  process.stderr.write(`[worktree-node_modules-link] ${line}\n`);
}

function runGit(args) {
  const r = spawnSync("git", args, {
    cwd: cwd(),
    encoding: "utf8",
    timeout: SPAWN_TIMEOUT_MS,
  });
  if (r.error || r.status !== 0) {
    return { ok: false, stdout: "", stderr: r.stderr ?? "" };
  }
  return { ok: true, stdout: r.stdout ?? "", stderr: r.stderr ?? "" };
}

function detectWorktree() {
  const r = runGit(["rev-parse", "--git-dir"]);
  if (!r.ok) return { ok: false };
  const gitDir = r.stdout.trim();
  const isMain = gitDir === ".git" || gitDir.endsWith("/.git") || gitDir.endsWith("\\.git");
  return { ok: true, isMain };
}

function getMainWorktreePath() {
  const r = runGit(["worktree", "list", "--porcelain"]);
  if (!r.ok) return null;
  const firstLine = r.stdout.split(/\r?\n/).find((l) => l.startsWith("worktree "));
  if (!firstLine) return null;
  return firstLine.slice("worktree ".length).trim();
}

function checkNodeModulesState(p) {
  let stat;
  try {
    stat = lstatSync(p);
  } catch {
    return "missing";
  }
  if (stat.isSymbolicLink()) {
    return existsSync(p) ? "symlink-ok" : "symlink-broken";
  }
  if (stat.isDirectory()) return "dir";
  return "file";
}

function createLink(target, linkPath) {
  if (process.platform === "win32") {
    const r = spawnSync("cmd.exe", ["/c", "mklink", "/J", linkPath, target], {
      encoding: "utf8",
      timeout: SPAWN_TIMEOUT_MS,
    });
    if (!r.error && r.status === 0) return { ok: true, method: "mklink /J" };
    const ps = spawnSync(
      "powershell.exe",
      [
        "-NoProfile",
        "-Command",
        `New-Item -ItemType Junction -Path "${linkPath}" -Target "${target}" | Out-Null`,
      ],
      { encoding: "utf8", timeout: SPAWN_TIMEOUT_MS },
    );
    if (!ps.error && ps.status === 0) return { ok: true, method: "New-Item Junction" };
    return { ok: false, method: "mklink/powershell", stderr: (r.stderr || ps.stderr || "").trim() };
  }
  const r = spawnSync("ln", ["-s", target, linkPath], {
    encoding: "utf8",
    timeout: SPAWN_TIMEOUT_MS,
  });
  if (!r.error && r.status === 0) return { ok: true, method: "ln -s" };
  return { ok: false, method: "ln -s", stderr: (r.stderr || "").trim() };
}

try {
  // Drain stdin so the hook event JSON is consumed without blocking.
  try {
    process.stdin.resume();
    process.stdin.on("data", () => {});
    process.stdin.on("error", () => {});
  } catch {
    /* noop */
  }

  const det = detectWorktree();
  if (!det.ok) {
    log("git rev-parse failed; skip");
    process.exit(0);
  }
  if (det.isMain) process.exit(0);

  const mainPath = getMainWorktreePath();
  if (!mainPath) {
    log("main worktree path not resolved; skip");
    process.exit(0);
  }

  const mainNodeModules = resolve(mainPath, "node_modules");
  if (!existsSync(mainNodeModules)) {
    log(`main node_modules not found: ${mainNodeModules}; skip`);
    process.exit(0);
  }

  const linkPath = resolve(cwd(), "node_modules");
  const state = checkNodeModulesState(linkPath);

  if (state === "dir") {
    process.exit(0);
  }
  if (state === "symlink-ok") {
    process.exit(0);
  }
  if (state === "file") {
    log(`node_modules is a file, not a directory: ${linkPath}; skip`);
    process.exit(0);
  }
  if (state === "symlink-broken") {
    try {
      unlinkSync(linkPath);
    } catch (e) {
      log(`failed to remove broken symlink: ${linkPath}: ${e?.message ?? "unknown"}; skip`);
      process.exit(0);
    }
  }

  const res = createLink(mainNodeModules, linkPath);
  if (res.ok) {
    log(`linked ${linkPath} -> ${mainNodeModules} (${res.method})`);
  } else {
    log(`link failed (${res.method}): ${linkPath} -> ${mainNodeModules}: ${res.stderr || "unknown"}`);
  }
  process.exit(0);
} catch (err) {
  log(`unexpected error: ${err?.message ?? "unknown"}`);
  process.exit(0);
}
